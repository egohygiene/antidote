def tex_escape(value: object) -> str:
    """Escape plain text for deterministic LaTeX."""
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character) for character in str(value))


def load_json(project: Path, relative: Path) -> dict[str, object]:
    """Load one repository-owned JSON object."""
    value = json.loads((project / relative).read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"expected JSON object: {relative}")
    return value


def evidence_rows(project: Path) -> list[tuple[str, str]]:
    """Read the five canonical evidence classes from EPISTEMOLOGY.md."""
    source = (project / EPISTEMOLOGY_PATH).read_text(encoding="utf-8")
    lines = source.splitlines()
    try:
        header_index = lines.index("| Layer | Meaning |")
    except ValueError as error:
        raise ValueError("cannot find the canonical five-row evidence table")
    candidates = lines[header_index + 2 : header_index + 7]
    rows: list[tuple[str, str]] = []
    for line in candidates:
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 2:
            rows.append((cells[0], cells[1]))
    if [name for name, _ in rows] != [
        "Source",
        "Hypothesis",
        "Observation",
        "Interpretation",
        "Claim",
    ]:
        raise ValueError("canonical evidence classes or ordering changed")
    return rows


def evidence_classification_table(project: Path) -> str:
    """Project evidence classes with support and promotion boundaries."""
    support = {
        "Source": "Primary or authoritative work plus a reviewed source record.",
        "Hypothesis": "Scoped rationale, uncertainty, and a testable research question.",
        "Observation": "A qualifying artifact, protocol, measurement, or person report.",
        "Interpretation": "Explicit reasoning linked to evidence and alternatives.",
        "Claim": "Ledger ID, named evidence, permitted wording, and review disposition.",
    }
    promotion = {
        "Source": "Supports only what the source establishes; never promotes itself to an Antidote claim.",
        "Hypothesis": "Remains tentative until qualifying observations and prespecified analysis exist.",
        "Observation": "Does not become an interpretation, outcome, or generalized claim automatically.",
        "Interpretation": "Must retain uncertainty, conflict, and plausible alternatives.",
        "Claim": "Must stay within its ledger boundary; otherwise downgrade, revise, or reject.",
    }
    lines = [
        "% Generated by scripts/generate_visual_tables.py.",
        "% Source: EPISTEMOLOGY.md and research/notes/CLAIM_LEDGER.md.",
        "% Do not edit this projection by hand.",
        r"\small",
        r"\setlength{\tabcolsep}{3.5pt}%",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.15\linewidth}>{\raggedright\arraybackslash}p{0.27\linewidth}>{\raggedright\arraybackslash}p{0.27\linewidth}>{\raggedright\arraybackslash}p{0.25\linewidth}@{}}",
        r"\toprule",
        r"\textbf{Class} & \textbf{Meaning} & \textbf{Acceptable support} & \textbf{Promotion boundary} \\",
        r"\midrule",
    ]
    for name, meaning in evidence_rows(project):
        lines.append(
            f"\\textbf{{{tex_escape(name)}}} & {tex_escape(meaning)} & "
            f"{tex_escape(support[name])} & {tex_escape(promotion[name])} \\\\"
        )
        lines.append(r"\addlinespace[0.32em]")
    lines.extend(
        (
            r"\bottomrule",
            r"\end{tabular}%",
            r"\par\smallskip",
            r"{\raggedright\scriptsize Each promotion is a separately reviewed decision. A generated explanation is not a source, and a synthetic fixture or compelling experience is not automatically a human-outcome result.\par}",
            "",
        )
    )
    return "\n".join(lines)


